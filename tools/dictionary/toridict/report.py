"""Coverage check (AQ-14) and build-report.md."""

import platform
import sqlite3
from pathlib import Path

from .text import match_key

SAMPLE_WORDS = 300
SAMPLE_PHRASES = 100
# A key is covered when the §6.2 lookup finds ≥ 1 Russian translation: exact headword key, else a form → base.
_COVERED = """
SELECT EXISTS (SELECT 1 FROM headword h JOIN translation_ru t ON t.headword_id = h.id WHERE h.key = :k)
    OR EXISTS (SELECT 1 FROM form f JOIN translation_ru t ON t.headword_id = f.headword_id WHERE f.form_key = :k)
"""


def coverage_list(folder: Path) -> tuple[Path, list[str]]:
    """`owner.txt` when present, else `placeholder.txt`. One item per line, `#` comments, blank lines ignored."""
    path = folder / "owner.txt"
    if not path.exists():
        path = folder / "placeholder.txt"
    items = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            items.append(line)
    return path, items


def sample_keys(items: list[str]) -> set[str]:
    keys = [match_key(i) for i in items]
    words = [k for k in keys if " " not in k][:SAMPLE_WORDS]
    phrases = [k for k in keys if " " in k][:SAMPLE_PHRASES]
    return set(words + phrases)


def coverage(db_path: Path, items: list[str]) -> dict:
    con = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True)
    out = {"words": [0, 0, []], "phrases": [0, 0, []]}
    for item in items:
        bucket = out["phrases" if " " in match_key(item) else "words"]
        bucket[1] += 1
        if con.execute(_COVERED, {"k": match_key(item)}).fetchone()[0]:
            bucket[0] += 1
        else:
            bucket[2].append(item)
    con.close()
    return out


def _counts(db_path: Path) -> dict[str, int]:
    con = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True)
    q = {
        "headword": "SELECT count(*) FROM headword",
        "headword (phrases)": "SELECT count(*) FROM headword WHERE is_phrase = 1",
        "headword with ≥ 1 RU translation": "SELECT count(DISTINCT headword_id) FROM translation_ru",
        "headword with freq_rank": "SELECT count(*) FROM headword WHERE freq_rank IS NOT NULL",
        "sense": "SELECT count(*) FROM sense",
        "translation_ru": "SELECT count(*) FROM translation_ru",
        "translation_ru (enwikt)": "SELECT count(*) FROM translation_ru WHERE origin = 'enwikt'",
        "translation_ru (ruwikt)": "SELECT count(*) FROM translation_ru WHERE origin = 'ruwikt'",
        "translation_ru tied to a sense": "SELECT count(*) FROM translation_ru WHERE sense_id IS NOT NULL",
        "form": "SELECT count(*) FROM form",
        "example": "SELECT count(*) FROM example",
        "related": "SELECT count(*) FROM related",
    }
    out = {k: con.execute(v).fetchone()[0] for k, v in q.items()}
    meta = dict(con.execute("SELECT key, value FROM meta"))
    con.close()
    return out | {"_meta": meta}


def _gzip_size(path: Path) -> int:
    import zlib
    z, n = zlib.compressobj(6, zlib.DEFLATED, 31), 0
    with open(path, "rb") as f:
        while chunk := f.read(1 << 20):
            n += len(z.compress(chunk))
    return n + len(z.flush())


def _pct(hit: int, total: int) -> str:
    return f"{hit}/{total} = {100 * hit / total:.1f} %" if total else "n/a"


def render(db_path: Path, digest: str, sources: dict, cov_list: tuple[Path, list[str]], sample: Path,
           seconds: float) -> str:
    counts = _counts(db_path)
    meta = counts.pop("_meta")
    cov = coverage(db_path, cov_list[1])
    size = db_path.stat().st_size
    sample_counts = _counts(sample)
    sample_counts.pop("_meta")
    lines = [
        f"# Dictionary build report — {meta['dictionary_version']}",
        "",
        "Generated by `uv run python -m toridict build` (doc 36 §8.1). Do not edit by hand.",
        "",
        "## Output",
        "",
        "| | |",
        "|---|---|",
        f"| File | `dictionary.sqlite` (GitHub Release asset `dictionary-{meta['dictionary_version']}`) |",
        f"| Size | {size:,} bytes ({size / 1048576:.1f} MiB; budget 60 MiB) |",
        f"| gzip -6 size | {_gzip_size(db_path):,} bytes (budget 25 MB compressed in the app package) |",
        f"| SHA-256 | `{digest}` |",
        f"| Prune step applied | `{meta['prune']}` (ladder: none → examples → related → rare-untranslated [§8.1] → untranslated-50k → -20k → -10k [extension]) |",
        f"| Build hash (`meta.build_hash`) | `{meta['build_hash']}` |",
        f"| Build time | {seconds:.0f} s on {platform.machine()} |",
        "",
        "## Coverage (AQ-14: target ≥ 90 % words, ≥ 60 % phrases with ≥ 1 Russian translation)",
        "",
        f"List: `{cov_list[0].relative_to(cov_list[0].parents[1])}`"
        + (" — **placeholder**, not the owner's real content; AQ-14 stays open." if cov_list[0].name == "placeholder.txt" else ""),
        "",
        "Covered = exact headword key, or a form key that leads to a base headword, with ≥ 1 `translation_ru` row.",
        "",
        f"- Words: {_pct(*cov['words'][:2])}",
        f"- Phrases: {_pct(*cov['phrases'][:2])}",
        "",
        "Missed words: " + (", ".join(cov["words"][2]) or "none"),
        "",
        "Missed phrases: " + (", ".join(cov["phrases"][2]) or "none"),
        "",
        "## Counts",
        "",
        "| Table / measure | Full | Sample |",
        "|---|---:|---:|",
        *(f"| {k} | {v:,} | {sample_counts[k]:,} |" for k, v in counts.items()),
        "",
        "## Inputs",
        "",
        "| Input | URL | Size | SHA-256 | Dump date | Extracted | wiktextract |",
        "|---|---|---:|---|---|---|---|",
        *(f"| {n} | {s['url']} | {s['size']:,} | `{s['sha256']}` | {s['dump_date']} | {s['extracted']} | {s['wiktextract']} |"
          for n, s in sorted(sources["inputs"].items())),
        "",
        "## Versions",
        "",
        f"- Python {meta['python_version']}, SQLite {meta['sqlite_version']}, wordfreq {meta['wordfreq_version']}",
        "",
        f"Sample: `ios/Resources/{sample.name}` (`{sample.stat().st_size:,}` bytes, version `{meta['dictionary_version']}-sample`).",
        "",
    ]
    return "\n".join(lines)
